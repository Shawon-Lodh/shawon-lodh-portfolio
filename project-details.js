function createListItems(targetEl, items) {
    targetEl.innerHTML = "";
    items.forEach((item) => {
        const li = document.createElement("li");
        li.textContent = item;
        targetEl.appendChild(li);
    });
}

function createTags(targetEl, tags) {
    targetEl.innerHTML = "";
    tags.forEach((tag) => {
        const span = document.createElement("span");
        span.textContent = tag;
        targetEl.appendChild(span);
    });
}

function createMetrics(targetEl, metrics) {
    targetEl.innerHTML = "";
    metrics.forEach((metric) => {
        const card = document.createElement("div");
        card.className = "metric-card";

        const value = document.createElement("span");
        value.className = "metric-value";
        value.textContent = metric.value;

        const label = document.createElement("span");
        label.className = "metric-label";
        label.textContent = metric.label;

        card.appendChild(value);
        card.appendChild(label);
        targetEl.appendChild(card);
    });
}

function createLinks(targetEl, links) {
    targetEl.innerHTML = "";

    links.forEach((link) => {
        const anchor = document.createElement("a");
        anchor.className = "details-link-btn";
        anchor.href = link.url;
        anchor.target = "_blank";
        anchor.rel = "noreferrer";
        anchor.innerHTML = `<i class="${link.icon}"></i> ${link.label}`;
        targetEl.appendChild(anchor);
    });
}

function showNotFound() {
    const detailsGrid = document.querySelector(".details-grid");
    const availableProjects = Object.entries(projects)
        .map(([slug, p]) => `<li><a href="project-details.html?project=${slug}">${p.title}</a></li>`)
        .join("");

    document.getElementById("project-title").textContent = "Project Not Found";
    document.getElementById("project-category").textContent = "Invalid Link";
    document.getElementById("project-summary").innerHTML = `
        The selected project is not available. Try one from this list:
        <ul class="details-list not-found" style="margin-top: 16px;">${availableProjects}</ul>
    `;
    document.getElementById("project-links").innerHTML = "";
    detailsGrid.innerHTML = "";
}

function renderProject(project) {
    document.title = `${project.title} | Project Details | Shawon Lodh`;

    document.getElementById("project-breadcrumb").textContent = project.title;
    document.getElementById("project-title").textContent = project.title;
    document.getElementById("project-category").textContent = project.category;
    document.getElementById("project-summary").textContent = project.summary;

    const iconEl = document.getElementById("project-icon");
    iconEl.className = project.icon;

    createMetrics(document.getElementById("project-metrics"), project.metrics);
    createListItems(document.getElementById("project-features"), project.features);
    createListItems(document.getElementById("project-responsibilities"), project.responsibilities);
    createListItems(document.getElementById("project-delivery"), project.delivery);
    createTags(document.getElementById("project-tech-stack"), project.techStack);
    createLinks(document.getElementById("project-links"), project.links);

    document.getElementById("project-role").textContent = project.role;
    document.getElementById("project-company").textContent = project.company;
    document.getElementById("project-platforms").textContent = project.platforms;
    document.getElementById("project-timeline").textContent = project.timeline;
}

const params = new URLSearchParams(window.location.search);
const slug = (params.get("project") || "magpie").toLowerCase();
const selectedProject = projects[slug];

if (!selectedProject) {
    showNotFound();
} else {
    renderProject(selectedProject);
}
